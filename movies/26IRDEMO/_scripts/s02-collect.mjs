// s02 · 검사 실시 (마인드봄) — 종이 채점지가 화면이 된다. 실시 화면만 보여준다.
// 배역: 검사 축 — **윤도현**. s01에서 접수한 그 아이의 로샤를 여기서 실시한다(마인드봄 seed:yun-rorschach).
// 임상가 정상담(clinician). 시작 URL: /examinations/<윤도현 로샤 examId>/collect
//
// 이 장면의 전부는 **임상가가 손으로 적는 것이 하나도 없다는 것**이다.
// 반응 **하나**를 두 바퀴 다 돌려 끝까지 채우고, 임상가 화면으로 돌아오면 이미 다 적혀 있다.
// (반응 둘을 돌린 판이 t11이다 — 39초로 편에 안 맞았다. 논지는 한 줄이면 선다.)
//
// ── 내담자 화면의 두 바퀴 (FreeAssociation.svelte:126-138) ──────────────────
// | 상태 | 카드 | 받아쓰기가 가는 곳 |
// |---|---|---|
// | 칩 미선택 = **자유반응** | 탭 판 — 누르면 새 줄 | 탭이 경계 → `free_association_text` |
// | 칩 선택 = **질문** | 그리기 판 — 영역을 그린다 | 고른 시각이 경계 → `inquiry_text` |
//
// 그래서 순서가 **말 → 탭 → 줄 생성**이고, **칩 선택 → 영역 → 말 → 질문 칸**이다.
// 영역을 고르는 것이 줄을 만드는 것은 아니다 — `handleDrawEnd`(640)는 고른 줄이 없으면
// 아무 일도 하지 않는다. 줄을 긋는 동작(탭)과 채우는 동작이 원래 별개다(§14-2).
//
// ── 조각의 주인 — 이 스크립트의 유일한 정밀 부품 ───────────────────────────
// 자유반응 바퀴: `routeClip`(706) — 조각이 시작된 뒤 **처음 찍힌 탭**의 줄로 간다.
// 질문 바퀴: `onText`(388) — **고른 뒤에 시작된** 말만 그 줄의 질문이 된다.
//
// ⚠️ 조각의 `startedAt`은 말이 시작된 시각이 아니라 **앞 조각이 끊긴 시각**이다
// (dictation.svelte.ts:144 — 녹음은 연속이고 침묵에서 잘린다). 그래서 칩을 고르는 시점과
// 조각의 주인이 한 칸씩 어긋난다. 대본의 **둘째 빈 줄**이 자유반응과 질문 사이 한 주기를 비운다.
//
// 목 마이크 주기 **3.7초**(말 1.2 + 침묵 2.4 — 2026-09-10 밤에 4.9에서 줄였다. `_mocks/s02-stt.json`).
// 이 주기가 장면의 길이를 정한다: 마지막 전사가 `2.5 + 2×주기`에 오고 그때까지 못 나간다(12.3s → 9.9s).
// 마이크를 켠 시각 M 기준으로:
//   말 시작 M+0.1 · +3.8 · +7.5        전사 도착 M+2.5 · +6.2 · +9.9
//   탭 M+0.9   칩 선택 M+3.7(조각 ③이 시작되는 M+6.2 전이면 된다)   영역 그리기 끝 M+6.3(전사 ③ 전)
//   임상가 화면 M+10.4(마지막 전사가 온 뒤 0.5초)
// 마지막 조각은 **내담자 화면 안에서** 받아야 한다 — 나가면서 `dictation.stop()`이 끊어 보내면
// 임상가 화면 경로로 들어가 `inquiry_stt_raw`가 안 남는다(onText:414). t10에서 실제로 잃었다.
export default async function steps(page, h) {
  // 전사가 도착한 것을 기다리는 유일한 방법 — 화면에는 표시가 없다.
  // 내담자 화면의 칩은 번호만 보여주고 받아쓴 말은 임상가 화면 팝오버의 textarea에 있다.
  // 그래서 목 전사 응답(installStt가 대본으로 답하는 그 요청) 자체를 조건으로 삼는다.
  const 전사 = (조각) => page.waitForResponse(
    async (r) => r.url().includes('transcribe-clip') && (await r.text()).includes(조각),
    { timeout: 20000 })

  // ① 오프닝 도착 — 관객이 화면을 알아볼 시간. s01은 여기에 0.71초를 준다(`beat`).
  //    여기는 기다릴 조건이 있으므로 `until` + 짧은 `hold`로 같은 길이를 만든다(settle 0.26 + 0.40).
  await h.until('button[aria-label^="내담자 화면"]', '로샤 실시 — 카드 I')
  await h.hold(400, '카드 I · 아직 빈 채점지')

  // ── 1바퀴: 자유반응 — 말이 먼저고, 탭이 그 말을 줄로 굳힌다 ────────────────
  h.nocutStart('말한 것이 그대로 반응이 된다')
  await h.click('button[aria-label^="내담자 화면"]', '내담자 화면 — 태블릿을 돌린다')
  await h.hold(350, '카드만 남는다 — 기록은 전부 가려진다')
  await h.click('button:has-text("받아쓰기")', '받아쓰기 — 마이크를 켠다')

  // 카드 어디를 눌러도 된다. 화면에는 숫자가 안 뜨고 잔물결만 퍼진다
  // (§14-2 — 반응 수가 보이면 피검자가 자기 페이스를 계산한다).
  //
  // ⚠️ **말이 전사돼 온 뒤에 탭한다. 그 반대가 아니다.** 목 마이크 WAV는 브라우저가 켜질 때부터
  //    루프하므로 마이크를 켠 시각과 파형의 위상이 매번 다르다. 고정 시각에 탭하면 그 탭이
  //    조각보다 앞설 때가 있고, 그러면 `routeClip`이 주인을 못 찾아(`tapAt >= startedAt` 불만족)
  //    조각이 `pendingClips`에 남는다 — **자유반응이 빈 줄로 저장된다. 화면에는 아무 표시도 없다.**
  //    2026-09-10에 같은 스크립트가 세 판 중 한 판씩 이렇게 깨졌다(t12가 통과한 것은 위상 운이었다).
  //
  //    전사가 먼저 오면 그 조각은 주인 없이 `pendingClips`에 담기고, **다음 탭이 회수한다**
  //    (FreeAssociation.svelte:514-524 — 제품이 "검사자가 뒤늦게 누른 경우"로 설계해 둔 경로다).
  //    그래서 줄은 생기는 순간부터 아이의 말을 담고 있다. 위상과 무관하게 매번 같다.
  const 자유반응도착 = 전사('박쥐')
  await 자유반응도착
  await h.click('button[aria-label^="반응 기록"]', '아이가 말하면 카드를 한 번 — 반응 ①')

  // ── 2바퀴: 질문 — 칩을 고르면 카드가 그리기 판이 된다 ─────────────────────
  // 남은 두 조각도 시각이 아니라 응답으로 기다린다. **칩 클릭 전에 둘 다 걸어둔다** —
  // 나중에 걸면 그 사이 도착한 응답을 놓쳐 20초를 헛기다린다.
  //   쉬는 조각(대본의 빈 줄) = 자유반응과 질문 사이를 비우는 한 주기. 제품은 빈 텍스트를 무시한다.
  //   그리기를 여기에 맞추면 그림이 끝나고 1초 뒤에 아이의 답이 온다 — 죽은 대기가 없다.
  const 쉬는조각 = 전사('"detected":false')
  const 질문도착 = 전사('날개요')
  await h.click('button[aria-label="반응 1 선택"]', '그 줄을 고른다 — 카드가 그리기 판이 된다')
  await 쉬는조각          // "어디가 그렇게 보였어?" — 검사자가 묻는 사이
  await h.drawOnCanvas('svg[aria-label="영역 그리기"]', [[0.42,0.34],[0.58,0.34],[0.62,0.55],[0.50,0.70],[0.38,0.55]], '아이가 가리킨 자리를 그린다')
  await 질문도착
  // 마지막 조각은 내담자 화면 안에서 받아야 `inquiry_stt_raw`가 남는다(onText:414) —
  // 도착한 뒤 화면에 붙는 시간만 두고 나간다. t10은 0.3초가 모자라 원문을 잃었다.
  await h.hold(500, '아이의 답이 그 줄의 질문 칸으로 들어간다')
  h.nocutEnd()

  // ── 임상가 화면 — 돌아오면 이미 다 적혀 있다 ──────────────────────────────
  // 칩은 고른 채로 나간다. 팝오버가 그대로 열려 있어 한 줄의 모든 칸이 한 화면에 보인다.
  h.nocutStart('돌아오면 이미 적혀 있다')
  await h.click('button[aria-label^="내담자 화면"]', '임상가 화면으로 돌아온다')
  // ③ **논지가 도착한 순간**은 짧게 둔다 — s01이 "폼이 갈아끼워진다"에 `beat`가 아니라 `hold(350)`을
  //    준 것과 같은 결정이다. 여기서 오래 멈추면 아직 아무것도 안 바뀐 화면을 쳐다보는 시간이 된다.
  await h.until('textarea[placeholder="피검자가 무엇으로 봤는지"]', '자유반응 · 질문 · 영역이 다 차 있다')
  await h.hold(350, '임상가가 받아친 것이 아니다')

  // 마지막 칸 — 위치 부호. 배지가 회색에서 초록으로 바뀌는 것이 이 장면의 작은 클라이맥스다(§14-12).
  //    `reveal`을 뺐다 — 팝오버가 뷰포트 안에 다 들어와 **스크롤이 실제로 일어나지 않고**(t13 실측 dy≈0)
  //    `beat` 0.7초만 남았다. 이미 보이는 것을 다시 보여주지 않는다(s01이 reveal 두 번을 스크롤 하나로 바꾼 것과 같은 판단).
  await h.click('button:has-text("W")', '위치 부호 W — 반점 전체')
  await h.beat('배지가 초록으로 — 빈 칸이 없다')
  h.nocutEnd()

  await h.hold(600, '끝')
}
