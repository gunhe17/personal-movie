# ── 그림 그리기 ──

def _wobble(rnd: random.Random, pts, amp: int = 4):
    """손그림처럼 좌표를 흔든다 — 검사마다 그림이 미묘하게 달라야 같은 파일로 안 보인다."""
    return [(x + rnd.randint(-amp, amp), y + rnd.randint(-amp, amp)) for x, y in pts]


def render(category: str, seed: str) -> bytes:
    """카테고리별 선화 PNG. 좌표는 PARTS와 같은 자리를 쓴다."""
    from PIL import Image, ImageDraw

    rnd = random.Random(seed + category)
    img = Image.new("RGB", (W, H), "white")
    d = ImageDraw.Draw(img)
    ink, lw = (40, 40, 45), 5

    def box(b, width=lw):
        x1, y1, x2, y2 = b
        d.line(_wobble(rnd, [(x1, y1), (x2, y1), (x2, y2), (x1, y2), (x1, y1)]),
               fill=ink, width=width, joint="curve")

    if category == "house":
        d.line(_wobble(rnd, [(250, 700), (525, 520), (800, 700)]), fill=ink, width=lw, joint="curve")
        box((300, 700, 750, 1060))
        box((640, 545, 700, 640))
        box((480, 880, 580, 1060))
        for wx1, wy1, wx2, wy2 in ((350, 760, 440, 850), (620, 760, 710, 850)):
            box((wx1, wy1, wx2, wy2), 3)
            d.line([((wx1 + wx2) // 2, wy1), ((wx1 + wx2) // 2, wy2)], fill=ink, width=3)
            d.line([(wx1, (wy1 + wy2) // 2), (wx2, (wy1 + wy2) // 2)], fill=ink, width=3)
        d.ellipse((520, 965, 545, 990), outline=ink, width=3)   # 손잡이
    elif category == "tree":
        d.ellipse((300, 430, 760, 830), outline=ink, width=lw)
        d.line([(495, 820), (490, 1080)], fill=ink, width=lw)
        d.line([(565, 820), (570, 1080)], fill=ink, width=lw)
        d.arc((430, 1030, 630, 1130), 20, 160, fill=ink, width=4)
        d.line([(300, 1085), (760, 1085)], fill=ink, width=3)   # 지면선
    else:
        d.ellipse((470, 415, 590, 545), outline=ink, width=lw)
        for ex1, ey1, ex2, ey2 in ((495, 462, 517, 480), (543, 462, 565, 480)):
            d.ellipse((ex1, ey1, ex2, ey2), outline=ink, width=3)
        d.line([(531, 490), (526, 512)], fill=ink, width=3)
        d.arc((505, 505, 555, 535), 20, 160, fill=ink, width=3)
        d.line([(515, 545), (517, 582)], fill=ink, width=4)
        d.line([(545, 545), (543, 582)], fill=ink, width=4)
        if category == "woman":
            d.line(_wobble(rnd, [(460, 582), (600, 582), (625, 860), (435, 860), (460, 582)]),
                   fill=ink, width=lw, joint="curve")
        else:
            box((460, 582, 600, 860))
        d.line(_wobble(rnd, [(462, 600), (420, 820)]), fill=ink, width=lw)
        d.line(_wobble(rnd, [(598, 600), (640, 820)]), fill=ink, width=lw)
        d.line(_wobble(rnd, [(495, 860), (490, 1150)]), fill=ink, width=lw)
        d.line(_wobble(rnd, [(565, 860), (570, 1150)]), fill=ink, width=lw)

    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()
