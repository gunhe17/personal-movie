def _make_doc(meta: dict) -> GlobalDocument:
    """캡처 메타 → GlobalDocument row (S3 객체는 사전 적재 가정)."""
    return GlobalDocument(
        name=meta["name"],
        original_name=meta.get("original_name"),
        file_type=meta["file_type"],
        storage_path=meta["storage_path"],
        file_size=meta.get("file_size") or 0,
        checksum=meta.get("checksum"),
    )


async def main() -> None:
    print("=" * 80)
    print("아동정서발달지원서비스 — 가공 완료 바우처 시드 (유일 가공 데이터)")
    print("=" * 80)

    cap = _CAPTURE
    now = datetime.now(timezone.utc).replace(tzinfo=None)

    async with AsyncSessionLocal() as session:
        # 멱등 — source pdf storage_path 로 중복 체크
        src_path = cap["source"]["storage_path"]
        existing = (
            await session.execute(
                select(GlobalDocument).where(
                    GlobalDocument.storage_path == src_path
                )
            )
        ).scalar_one_or_none()
        if existing is not None:
            print(f"\n⏭  이미 존재 (source pdf id={existing.id}) — 스킵")
            return

        # [1] source PDF global_document
        pdf = _make_doc(cap["source"])
        session.add(pdf)
        await session.flush()
        await session.refresh(pdf)

        # [2] artifacts → global_documents (md + 서식 PNG), page→png id 매핑 보존
        artifact_ids: list[str] = []
        png_id_by_page: dict[str, str] = {}
        for art in cap["artifacts"]:
            doc = _make_doc(art)
            session.add(doc)
            await session.flush()
            await session.refresh(doc)
            artifact_ids.append(doc.id)
            if art["role"] == "png" and art.get("page"):
                png_id_by_page[art["page"]] = doc.id

        # [3] forms 재링크 — 캡처의 page/title/kind 에 새 PNG global_document id 부여
        forms = [
            {
                "page": f.get("page"),
                "title": f.get("title"),
                "kind": f.get("kind"),
                "global_document_id": png_id_by_page.get(f.get("page")),
            }
            for f in cap.get("forms", [])
        ]

        # [4] voucher_extractions(completed)
        extraction = VoucherExtraction(
            status=VoucherExtractionStatus.COMPLETED,
            started_at=now,
            completed_at=now,
            source_document_ids=[pdf.id],
            artifact_document_ids=artifact_ids,
            completed={
                "type": cap.get("type"),
                "source_url": cap.get("source_url"),
                "meta": cap.get("meta") or {},
                "vouchers": cap.get("vouchers", []),
                "forms": forms,
            },
        )
        session.add(extraction)
        await session.flush()
        await session.refresh(extraction)
        await session.commit()

        print("\n✅ 생성")
        print(f"   - source pdf  : {pdf.id}  ({pdf.storage_path})")
        print(
            f"   - artifacts   : md+png {len(artifact_ids)}개 "
            f"({', '.join(artifact_ids)})"
        )
        print(
            f"   - extraction  : {extraction.id} (completed, "
            f"vouchers={len(cap.get('vouchers', []))}, forms={len(forms)})"
        )

    print("\n" + "=" * 80)
    print("✅ 완료")
    print("=" * 80)


if __name__ == "__main__":
    asyncio.run(main())
