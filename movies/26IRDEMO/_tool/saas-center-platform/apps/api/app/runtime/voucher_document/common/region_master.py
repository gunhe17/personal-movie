def _units(m: dict) -> list[str]:
    return m.get("시", []) + m.get("군", []) + m.get("자치구", []) + m.get("행정시", [])


ALL_PAIRS: list[dict[str, str | None]] = [
    {"시도": sido, "시군구": u}
    for sido, m in MASTER.items()
    for u in (_units(m) or [None])
]

# 시군구명 → 소속 시도 목록 (동명 다수: "중구" 등 — 길이 >1 이면 모호)
UNIT_TO_SIDOS: dict[str, list[str]] = {}
for _sido, _m in MASTER.items():
    for _u in _units(_m):
        UNIT_TO_SIDOS.setdefault(_u, []).append(_sido)


def resolve_unit(name: str) -> tuple[str, str] | None:
    """시군구 표기 → (시도, 시군구). 동명 모호(전국 유일 아님)·미상이면 None."""
    name = name.strip()
    if not name.endswith(("시", "군", "구")):
        name_full = None
        for suffix in ("시", "군", "구"):
            if name + suffix in UNIT_TO_SIDOS:
                name_full = name + suffix
                break
        if name_full is None:
            return None
        name = name_full
    sidos = UNIT_TO_SIDOS.get(name)
    if not sidos:
        return None
    if len(sidos) == 1:
        return sidos[0], name
    return None


def expand_region_from_capture(
    region: dict | None,
) -> list[dict[str, str | None]]:
    """capture.지역 → 앱이 쓸 추진지역 목록 (**파생**, 정본 아님).

    D16:
    - 전국 true → ALL_PAIRS (마스터 전 지역). capture.지역들에 쓰지 말 것.
    - 아니면 지역들 중 mark≠X 인 이름만 resolve_unit 결속. 미결속은 건너뜀.
    """
    if not isinstance(region, dict):
        return []
    if region.get("전국") is True:
        return list(ALL_PAIRS)
    out: list[dict[str, str | None]] = []
    for u in region.get("지역들") or []:
        if not isinstance(u, dict):
            continue
        if u.get("mark") == "X":
            continue
        name = (u.get("이름") or "").strip()
        if not name:
            continue
        hit = resolve_unit(name)
        if hit:
            out.append({"시도": hit[0], "시군구": hit[1]})
    return out
