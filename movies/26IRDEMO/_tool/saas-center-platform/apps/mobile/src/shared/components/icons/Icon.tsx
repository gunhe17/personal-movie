export type IconName = keyof typeof ICON_MAP;

export interface IconProps {
  name: IconName;
  size?: number;
  color?: string;
}

export function Icon({ name, size = 24, color = COLORS.gray[700] }: IconProps) {
  const SvgIcon = ICON_MAP[name] as React.FC<SvgProps> | undefined;
  if (!SvgIcon) {
    if (__DEV__) {
      console.warn(`[Icon] "${name}" 아이콘이 등록되지 않았습니다.`);
    }
    return null;
  }
  return <SvgIcon width={size} height={size} color={color} />;
}
